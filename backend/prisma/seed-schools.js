async function main() {
  console.log("🌱 Starting school seeder for 50 schools...");

  for (let i = 0; i < schoolsData.length; i++) {
    const schoolData = schoolsData[i];
    const adminId = i + 1; // Map school admin 1 to school 1, admin 2 to school 2, etc.

    try {
      const school = await prisma.school.create({
        data: {
          adminId: adminId,
          schoolName: schoolData.school_name,
          contactEmail: schoolData.contact_email,
          contactPhone: schoolData.contact_phone,
          curriculum: mapCurriculum(schoolData.curriculum),
          tuitionFee: schoolData.tuition_fee,
          facilities: schoolData.facilities || null,
          verificationStatus: mapVerificationStatus(schoolData.verification_status),
          latitude: schoolData.latitude,
          longitude: schoolData.longitude,
          createdAt: new Date(schoolData.created_at),
          updatedAt: new Date(schoolData.updated_at),
          rating: schoolData.rating,
          reviewCount: schoolData.review_count,
          schoolLevel: mapSchoolLevel(schoolData.school_level),
          schoolType: mapSchoolType(schoolData.school_type),
          streetName: schoolData.street_name,
          subCity: mapSubCity(schoolData.sub_city),
          woreda: schoolData.woreda,
          totalAchievementScore: schoolData.total_achievement_score,
        },
      });

      // Create school demographics if national exam score or passing rate is provided
      if (schoolData.national_exam_score || schoolData.passing_rate) {
        await prisma.schoolDemographics.create({
          data: {
            schoolId: school.id,
            academicYear: 2025,
            totalStudents: 500, // Default value since not provided
            girlsCount: 250, // Default value since not provided
            boysCount: 250, // Default value since not provided
            passingRate: schoolData.passing_rate || 0,
            nationalExamScore: schoolData.national_exam_score || 0,
          },
        });
      }

      console.log(`✅ Seeded school ${i + 1}: ${schoolData.school_name} with admin ID ${adminId}`);
    } catch (error) {
      console.error(`❌ Error seeding school ${i + 1} (${schoolData.school_name}):`, error.message);
    }
  }

  console.log("🏁 School seeding completed.");
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });